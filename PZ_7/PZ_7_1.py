# Объединение частей двух строк

n1 = int(input('Введите число N1: '))
n2 = int(input('Введите число N2: '))

s1 = input('Введите строку S1: ')
s2 = input('Введите строку S2: ')

new_string = s1[:n1] + s2[-n2:]

print('Исходная строка S1:', s1)
print('Исходная строка S2:', s2)
print('Полученная строка:', new_string)