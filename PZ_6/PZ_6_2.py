# Создание нового списка из элементов
# с нечётными порядковыми номерами

n = int(input('Введите размер списка: '))

a = []
i = 0

while i < n:
    a.append(int(input('Введите элемент списка: ')))
    i += 1

b = a[::2]

print('Исходный список A:', a)
print('Полученный список B:', b)
print('Размер списка B:', len(b))