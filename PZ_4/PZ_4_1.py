# Вывести в порядке убывания все целые числа между A и B и их количество N
a = int(input("Введите A: "))
b = int(input("Введите B: "))

# По условию A должно быть меньше B, иначе спрашиваем заново
while a >= b:
    print("A должно быть меньше B")
    a = int(input("Введите A: "))
    b = int(input("Введите B: "))

n = 0
# Идём от B - 1 вниз до A + 1 (сами A и B не выводим)
for i in range(b - 1, a, -1):
    print(i)
    n += 1

print("Количество чисел N =", n)


