# Дано целое N (> 1). Найти наибольшее K, для которого 1 + 2 + ... + K <= N,
# и вывести K и саму сумму

n = int(input("Введите N (N > 1): "))
while n <= 1:
    n = int(input("N должно быть больше 1. Введите ещё раз: "))

k = 0
s = 0
# Добавляем следующее слагаемое, пока сумма не превысит N
while s + k + 1 <= n:
    k += 1
    s += k

print("K =", k)
print("Сумма 1 + 2 + ... + K =", s)