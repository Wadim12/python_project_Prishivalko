#Дано целое число N (> 1). Программа находит наибольшее целое K,
#для которого сумма 1 + 2 + ... + K меньше или равна N, и выводит
#это K и саму сумму.



def read_int(prompt):
    #Запрашивает у пользователя целое число.Запрос повторяется до тех пор, пока не будет введено корректное
    #целое число. Возвращает введённое число (тип int).

    while True:
        try:
            return int(input(prompt))
        except ValueError:
            print("Неправильно ввели!")


def main():
    # Ввод числа N. По условию N > 1
    n = read_int("Введите N (N > 1): ")
    while n <= 1:
        print("Должно выполняться N > 1!")
        n = read_int("Введите N (N > 1): ")

    k = 0
    total = 0

    # Добавляем следующее слагаемое, пока сумма не превысит N
    while total + (k + 1) <= n:
        k += 1
        total += k

    # Вывод результата
    print("K =", k)
    print("Сумма 1 + 2 + ... + K =", total)


if __name__ == "__main__":
    main()

