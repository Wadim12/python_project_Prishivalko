def main():
    #Выполняет основную программу.
    try:
        n = int(input("Введите количество секунд с начала суток: "))

        if n < 0 or n >= 86400:
            print("Ошибка: число должно быть от 0 до 86399.")
            return

        # Находим остаток от деления на 60.
        seconds = n % 60

        # Выводим результат.
        print("Секунд с начала последней минуты:", seconds)

    except ValueError:
        print("Ошибка: необходимо ввести целое число.")

if __name__ == "__main__":
    main()